fun main() {
    //arithmetic operators
    var x=100
    var y=5
    println(x-y)
    println(x+y)
    println(x*y)
    println(x/y)
    println(x % y)//modulus
    //comparison operators
    var A=45
    var B=3
    println(A<B)
    println(A>B)
    println(A>=B)
    println(A<=B)
    println(A==B)
    println(A!=B)
    //Assignment operators
    var number=90
    println(number)
    number +=2
    println(number)
    //logical operators -&&,||,!
    var num =78
    println(num < 10 && num>20)
    println(num < 10 || num>20)




}